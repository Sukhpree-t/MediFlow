-- ============================================================
-- MediFlow V1 — Database Schema Initialization
-- Schema: app (isolated from Supabase public schema)
-- Standard ANSI / PostgreSQL / H2 compatible
-- ============================================================

CREATE SCHEMA IF NOT EXISTS app;

-- ============================================================
-- Table: app.staff_users
-- ============================================================
CREATE TABLE IF NOT EXISTS app.staff_users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id       VARCHAR(50)  NOT NULL UNIQUE,
    full_name         VARCHAR(150) NOT NULL,
    email             VARCHAR(255) NOT NULL UNIQUE,
    password_hash     VARCHAR(255) NOT NULL,
    role              VARCHAR(50)  NOT NULL
        CHECK (role IN ('ROLE_ER_COORDINATOR','ROLE_WARD_NURSE','ROLE_ADMIN')),
    assigned_terminal VARCHAR(50),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- Table: app.beds
-- version BIGINT for JPA @Version optimistic locking
-- ============================================================
CREATE TABLE IF NOT EXISTS app.beds (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bed_code       VARCHAR(20)  NOT NULL UNIQUE,
    ward_type      VARCHAR(20)  NOT NULL
        CHECK (ward_type IN ('ICU','GENERAL','ISOLATION')),
    floor_number   INT          NOT NULL DEFAULT 1,
    status         VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN ('AVAILABLE','OCCUPIED','CLEANING','RESERVED')),
    has_ventilator BOOLEAN      NOT NULL DEFAULT FALSE,
    version        BIGINT       NOT NULL DEFAULT 1,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_beds_status    ON app.beds (status);
CREATE INDEX IF NOT EXISTS idx_beds_ward_type ON app.beds (ward_type);

-- ============================================================
-- Table: app.patients
-- ============================================================
CREATE TABLE IF NOT EXISTS app.patients (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code     VARCHAR(30)  NOT NULL UNIQUE,
    full_name        VARCHAR(150) NOT NULL,
    age              INT          NOT NULL CHECK (age > 0 AND age < 150),
    gender           VARCHAR(10)  NOT NULL CHECK (gender IN ('M','F','OTHER')),
    chief_complaint  TEXT         NOT NULL,
    vitals_summary   TEXT,
    acuity_level     INT          NOT NULL CHECK (acuity_level BETWEEN 1 AND 4),
    recommended_ward VARCHAR(20)  CHECK (recommended_ward IN ('ICU','GENERAL','ISOLATION')),
    status           VARCHAR(20)  NOT NULL DEFAULT 'WAITING'
        CHECK (status IN ('WAITING','ADMITTED','DISCHARGED')),
    arrival_time     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_patients_status ON app.patients (status);

-- ============================================================
-- Table: app.admissions
-- ============================================================
CREATE TABLE IF NOT EXISTS app.admissions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bed_id               BIGINT       NOT NULL REFERENCES app.beds(id),
    patient_id           BIGINT       NOT NULL REFERENCES app.patients(id),
    admitted_by_staff_id BIGINT       NOT NULL REFERENCES app.staff_users(id),
    attending_doctor     VARCHAR(150),
    admitted_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    discharged_at        TIMESTAMP WITH TIME ZONE,
    notes                TEXT
);

CREATE INDEX IF NOT EXISTS idx_admissions_bed_id     ON app.admissions (bed_id);
CREATE INDEX IF NOT EXISTS idx_admissions_patient_id ON app.admissions (patient_id);
CREATE INDEX IF NOT EXISTS idx_admissions_discharged ON app.admissions (discharged_at);

-- ============================================================
-- Table: app.audit_logs
-- ============================================================
CREATE TABLE IF NOT EXISTS app.audit_logs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id        VARCHAR(50),
    action_type        VARCHAR(50)  NOT NULL,
    bed_code           VARCHAR(20),
    version_transition VARCHAR(30),
    staff_role         VARCHAR(50),
    latency_ms         BIGINT,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at  ON app.audit_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action_type ON app.audit_logs (action_type);
